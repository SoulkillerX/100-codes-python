Num=int(input("Enter a number (1-7) to get the corresponding day of the week: "))
if Num==1:
    print("Monday")
elif Num==2:
    print("Tuesday")
elif Num==3:
    print("Wednesday")
elif Num==4:
    print("Thursday")
elif Num==5:
    print("Friday")
elif Num==6:
    print("Saturday")
elif Num==7:
    print("Sunday")
else:
    print("Invalid input. Please enter a number between 1 and 7.")